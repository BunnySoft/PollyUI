import { readFileSync, writeFileSync } from 'node:fs';
import { DEFAULT_DESKTOP_THEME, DESKTOP_THEMES } from '../shell/themes.mjs';

const fields = ['border', 'titleFrom', 'titleTo', 'titleText', 'inactiveFrom', 'inactiveTo',
  'inactiveText', 'controlFrom', 'controlTo', 'closeFrom', 'closeTo', 'controlText'];
const number = value => {
  if (!Number.isInteger(value) || value < 0 || value > 64) throw new Error('Invalid decoration dimension');
  return String(value);
};
const color = value => {
  if (!/^#[0-9a-f]{6}$/i.test(value)) throw new Error('Invalid decoration color');
  return '0xff' + value.slice(1) + 'u';
};
const defaultTheme = DESKTOP_THEMES.findIndex(theme => theme.id === DEFAULT_DESKTOP_THEME);
if (defaultTheme < 0) throw new Error('Missing default decoration theme');
const text = `/* Generated by desktop/tools/generate-decoration-themes.mjs. */
#ifndef POLLYWM_DECORATION_THEMES_H
#define POLLYWM_DECORATION_THEMES_H
#include <stdbool.h>
#include <stdint.h>

struct PuDecorationTheme {
    const char *id;
    int border_width, title_height, radius;
    bool left_controls, round_controls, pinstripe;
    uint32_t ${fields.join(', ')};
};
static const struct PuDecorationTheme pu_decoration_themes[] = {
${DESKTOP_THEMES.map(theme => {
  if (!/^[a-z0-9]+$/.test(theme.id)) throw new Error('Invalid theme ID');
  const w = theme.window;
  return `    { "${theme.id}", ${[w.borderWidth, w.titleHeight, w.radius].map(number).join(', ')},
      ${w.controls === 'left'}, ${w.controlShape === 'round'}, ${w.texture === 'pinstripe'},
      ${fields.map(key => color(w[key])).join(', ')} },`;
}).join('\n')}
};
#define PU_DECORATION_THEME_COUNT (sizeof(pu_decoration_themes) / sizeof(pu_decoration_themes[0]))
#define PU_DECORATION_DEFAULT_THEME ${defaultTheme}
#endif
`;
const output = new URL('../compositor/decoration-themes.h', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== text)
    throw new Error('Decoration tokens are stale; regenerate them');
} else {
  writeFileSync(output, text);
}
