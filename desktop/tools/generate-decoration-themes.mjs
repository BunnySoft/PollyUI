import { readFileSync, writeFileSync } from 'node:fs';
import { DEFAULT_DESKTOP_THEME, DESKTOP_THEMES } from '../shared/ui/themes.mjs';
import { DECORATION_LAYOUT_FIELDS, decorationLayout } from '../shared/ui/caption-layout.mjs';

const defaultTheme = DESKTOP_THEMES.findIndex(theme => theme.id === DEFAULT_DESKTOP_THEME);
if (defaultTheme < 0) throw new Error('Missing default decoration layout');
const schema = `/* Generated geometry schema. Visual policy remains in the GUI. */
#ifndef POLLY_APPEARANCE_FIELDS_H
#define POLLY_APPEARANCE_FIELDS_H
#define PU_APPEARANCE_METRICS(X) \\
${DECORATION_LAYOUT_FIELDS.map(([field, token, minimum, maximum, scale]) =>
  `    X(int, ${field}, ${token}, ${minimum}, ${maximum}, ${scale})`).join(' \\\n')}
#endif
`;
const text = `/* Generated by desktop/tools/generate-decoration-themes.mjs. Geometry only. */
#ifndef POLLY_TEST_DECORATION_LAYOUTS_H
#define POLLY_TEST_DECORATION_LAYOUTS_H
#include "appearance-config.h"
static const struct PuDecorationPreset {
    const char *id;
    struct PuDecorationLayout layout;
} pu_decoration_layouts[] = {
${DESKTOP_THEMES.map(theme => {
  if (!/^[a-z0-9]+$/.test(theme.id)) throw new Error('Invalid theme ID');
  const layout = decorationLayout(theme);
  for (const [field, , min, max] of DECORATION_LAYOUT_FIELDS)
    if (!Number.isInteger(layout[field]) || layout[field] < min || layout[field] > max)
      throw new Error(`Invalid decoration geometry: ${field}`);
  return `    { .id = "${theme.id}", .layout = { .left_controls = ${layout.left_controls},
      ${DECORATION_LAYOUT_FIELDS.map(([field]) => `.${field} = ${layout[field]}`).join(', ')} } },`;
}).join('\n')}
};
#define PU_DECORATION_LAYOUT_COUNT (sizeof(pu_decoration_layouts) / sizeof(pu_decoration_layouts[0]))
#define PU_DECORATION_DEFAULT_LAYOUT ${defaultTheme}
#endif
`;
for (const [file, content] of [['../tests/decoration-layout-fixtures.h', text], ['../shared/appearance-fields.h', schema]]) {
  const output = new URL(file, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== content)
      throw new Error('Decoration geometry is stale; regenerate it');
  } else writeFileSync(output, content);
}
