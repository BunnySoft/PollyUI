import * as THREE from "gui/tests/gpu/node_modules/three/build/three.webgpu.js";
function check(value,message){if(!value)throw Error(message);}
const main=window.create({title:"GpuCanvas.mapped",width:200,height:160});
const document=main.document;
Object.assign(document.body.style,{backgroundColor:"white",alignItems:"flex-start"});
const clip=document.createElement("view");
Object.assign(clip.style,{position:"absolute",left:"10",top:"10",width:"30",height:"20",overflow:"hidden",scrollLeft:"2"});
const canvas=document.createElement("canvas");canvas.width=canvas.height=8;
Object.assign(canvas.style,{width:"40",height:"40",borderRadius:"8",translateX:"2"});
clip.appendChild(canvas);document.body.appendChild(clip);
const renderer=new THREE.WebGPURenderer({canvas,antialias:false,alpha:false});
await renderer.init();check(renderer.backend.isWebGPUBackend,"mapped original Three uses native WebGPU, not fallback");
renderer.setSize(8,8,false);
const scene=new THREE.Scene(),camera=new THREE.OrthographicCamera(-1,1,1,-1,.1,10);
camera.position.z=4;
const geometry=new THREE.PlaneGeometry(2,2),material=new THREE.MeshBasicMaterial({color:0xff0000});
scene.add(new THREE.Mesh(geometry,material));
await renderer.renderAsync(scene,camera);
const source=document.createElement("canvas");source.width=source.height=2;
source.getContext("2d").fillStyle="blue";source.getContext("2d").fillRect(0,0,2,2);
const image=new Image();image.src=source.toDataURL();await image.decode();
Object.assign(image.style,{position:"absolute",left:"60",top:"10",width:"10",height:"10"});
document.body.appendChild(image);
const overlay=document.createElement("canvas");overlay.width=overlay.height=4;
Object.assign(overlay.style,{position:"absolute",left:"100",top:"10",width:"20",height:"20",opacity:".5"});
const context=overlay.getContext("webgpu");context.configure({device:renderer.backend.device,format:"rgba8unorm"});
const encoder=renderer.backend.device.createCommandEncoder();
const pass=encoder.beginRenderPass({colorAttachments:[{view:context.getCurrentTexture(),loadOp:"clear",storeOp:"store",clearValue:[1,0,0,1]}]});
pass.end();renderer.backend.device.queue.submit([encoder.finish()]);document.body.appendChild(overlay);
const control=document.createElement("canvas");control.width=control.height=4;
Object.assign(control.style,{position:"absolute",left:"130",top:"10",width:"20",height:"20",opacity:".5"});
control.getContext("2d").fillStyle="red";control.getContext("2d").fillRect(0,0,4,4);document.body.appendChild(control);
canvas.addEventListener("mousedown",async event=>{
    check(Math.abs(event.clientX-20)<1&&Math.abs(event.clientY-20)<1,"mapped compositor delivers logical WebGPU canvas input at actual 1.5 DPI");
    check(canvas.width===8&&canvas.height===8,"native output DPI does not alter WebGPU backing dimensions");
    material.color.set(0x00ff00);await renderer.renderAsync(scene,camera);
    console.log("PASS: mapped unmodified Three WebGPU/input, actual fractional scale, clip/scroll/transform/opacity");
    setTimeout(()=>{context.unconfigure();geometry.dispose();material.dispose();renderer.dispose();window.quit();},150);
});
setTimeout(()=>{console.error("FAIL: mapped native WebGPU input timed out");window.quit();},8000);
