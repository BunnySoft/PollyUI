import {readFileSync,writeFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {resolve} from "node:path";

const [commonFile,webgl2File,output,interfaceOutput]=process.argv.slice(2);
if(!commonFile||!webgl2File||!output)throw new Error("usage: node generate-api.mjs common.idl webgl2.idl output.mjs");
const revision="714857a28445e8f5d8d6ae1c78498578009534d8";
const sources=[commonFile,webgl2File].map(path=>({path,text:readFileSync(path,"utf8")}));
function mixin(text,name){
    const match=new RegExp(`interface mixin ${name}\\s*\\{([\\s\\S]*?)\\n\\};`).exec(text);
    if(!match)throw new Error("Missing pinned IDL mixin: "+name);
    return match[1].replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g,"");
}
const text=[mixin(sources[0].text,"WebGLRenderingContextBase"),
    mixin(sources[1].text,"WebGL2RenderingContextBase"),mixin(sources[1].text,"WebGL2RenderingContextOverloads")].join("\n");
const constants={},methods={},attributes=[];
for(const member of text.split(";").map(s=>s.trim()).filter(Boolean)){
    const constant=/^const\s+\w+\s+(\w+)\s*=\s*([^;]+)$/.exec(member);
    if(constant){constants[constant[1]]=Number(constant[2]);continue;}
    const attribute=/^(readonly\s+)?attribute\s+([\s\S]+?)\s+(\w+)$/.exec(member);
    if(attribute){attributes.push({name:attribute[3],type:attribute[2],readonly:Boolean(attribute[1])});continue;}
    const operation=/^(?:\[([^\]]+)\]\s*)?([\s\S]+?)\s+(\w+)\s*\(([\s\S]*)\)$/.exec(member);
    if(!operation)throw new Error("Unparsed pinned IDL member: "+member);
    const params=operation[4].split(/,(?![^<>]*>)/).map(s=>s.trim()).filter(Boolean);
    const required=params.filter(s=>!s.startsWith("optional ")).length;
    const method={returns:operation[2].replace(/\s+/g," "),required,handlesLoss:Boolean(operation[1]?.includes("WebGLHandlesContextLoss")),
        parameters:params};
    (methods[operation[3]]??=[]).push(method);
}
const license=sources[0].text.slice(sources[0].text.indexOf("// Copyright"),sources[0].text.indexOf("typedef "));
const result={specification:"WebGL 2.0 + inherited WebGLRenderingContextBase (not a WebGL1 context)",
    revision,sourceUrls:["specs/latest/1.0/webgl.idl","specs/latest/2.0/webgl2.idl"].map(p=>`https://raw.githubusercontent.com/KhronosGroup/WebGL/${revision}/${p}`),
    sourceSha256:sources.map(s=>createHash("sha256").update(s.text).digest("hex")),license,
    constants,attributes,methods};
writeFileSync(resolve(output),"// Generated by generate-api.mjs from the pinned, licensed Khronos IDL inputs.\nexport default "+
    JSON.stringify(result,null,2)+";\n");
console.log(JSON.stringify({constants:Object.keys(constants).length,attributes:attributes.length,methods:Object.keys(methods).length,
    overloads:Object.values(methods).reduce((sum,list)=>sum+list.length,0),revision}));
if(interfaceOutput){
    const descriptors=Object.fromEntries(Object.entries(methods).map(([name,list])=>[name,{
        required:Math.min(...list.map(method=>method.required)),returns:list[0].returns,
        handlesLoss:list.some(method=>method.handlesLoss)
    }]));
    writeFileSync(resolve(interfaceOutput),"// Generated by gui/tests/gpu/generate-api.mjs from Khronos WebGL IDL.\n"+
        license+"// Revision: "+revision+"\n("+JSON.stringify(descriptors,null,2)+")\n");
}
