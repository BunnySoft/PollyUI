#!/usr/bin/env python3
"""Original Polly rabbit cursor masters -> deterministic companion PNG and masks."""
import argparse
import base64
import importlib.util
import json
from pathlib import Path
import struct
import zlib

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("polly_cursors", HERE / "generate-cursors.py")
cursors = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cursors)
ROOT = HERE.parent / "resources/companions"


def rectangles(pixels):
    result, previous = [], {}
    for y in range(32):
        runs = []
        x = 0
        while x < 32:
            if pixels[y * 32 + x] >> 24:
                start = x
                while x < 32 and pixels[y * 32 + x] >> 24:
                    x += 1
                runs.append((start * 3, (x - start) * 3))
            else:
                x += 1
        current = {}
        for x, width in runs:
            old = previous.get((x, width))
            if old is None:
                old = len(result)
                result.append([x, y * 3, width, 3])
            else:
                result[old][3] += 3
            current[(x, width)] = old
        previous = current
    if len(result) > 63:
        raise ValueError("Companion input masks exceed the native budget")
    return result


def generate():
    frames, masks = [], []
    for name, frame in [("default", 0), ("click", 1), ("click", 2), ("click", 3),
                        ("motion", 0), ("motion", 1), ("motion", 2), ("motion", 3)]:
        pixels, _ = cursors.rabbit(name, frame)
        for y in range(16, 21):
            for x in range(2, 7):
                pixels[y * 32 + x] = 0
        frames.append(pixels)
        masks.append(rectangles(pixels))
    rows = bytearray()
    for y in range(96):
        rows.append(0)
        for frame in frames:
            for x in range(96):
                pixel = frame[(y // 3) * 32 + x // 3]
                rows.extend((pixel >> 16 & 255, pixel >> 8 & 255, pixel & 255, pixel >> 24))
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 768, 96, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b"")
    module = "// Generated by desktop/tools/generate-companion.py from original Polly artwork.\n"
    module += "export const companionAtlas = 'data:image/png;base64," + base64.b64encode(png).decode() + "';\n"
    module += "export const companionMasks = " + json.dumps(masks, separators=(",", ":")) + ";\n"
    return {"polly-rabbit.png": png, "polly-rabbit.mjs": module.encode()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    outputs = generate()
    if args.write:
        ROOT.mkdir(parents=True, exist_ok=True)
        for name, data in outputs.items():
            (ROOT / name).write_bytes(data)
    else:
        for name, data in outputs.items():
            if (ROOT / name).read_bytes() != data:
                raise SystemExit("Stale original companion resource: " + name)
    print("PASS: original companion PNG, exact alpha input masks and deterministic resource pairing")
