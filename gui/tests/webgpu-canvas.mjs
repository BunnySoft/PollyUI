function check(value,message){if(!value)throw Error(message);}
const adapter=await navigator.gpu.requestAdapter();
const device=await adapter.requestDevice();
const canvas=document.createElement("canvas");canvas.width=8;canvas.height=8;
const context=canvas.getContext("webgpu");
check(context instanceof GPUCanvasContext && context===canvas.getContext("webgpu"),"real stable WebGPU canvas context");
check(canvas.getContext("2d")===null&&canvas.getContext("webgl2")===null,"context modes remain exclusive");
context.configure({device,format:"bgra8unorm",alphaMode:"opaque"});
const first=context.getCurrentTexture();
check(first===context.getCurrentTexture()&&first.width===8&&first.usage===GPUTextureUsage.RENDER_ATTACHMENT,"current texture identity/backing/usage");
const encoder=device.createCommandEncoder();
const pass=encoder.beginRenderPass({colorAttachments:[{view:first.createView(),loadOp:"clear",storeOp:"store",clearValue:[1,0,0,1]}]});
pass.end();device.queue.submit([encoder.finish()]);
const output=document.createElement("canvas");output.width=8;output.height=8;
const raster=output.getContext("2d");raster.drawImage(canvas,0,0);
check([...raster.getImageData(3,3,1,1).data].join()==="255,0,0,255","real native BGRA canvas source feeds 2D snapshot");
check(canvas.toDataURL().startsWith("data:image/png;base64,"),"native source exports bounded PNG");
canvas.width=4;
const resized=context.getCurrentTexture();
check(resized!==first&&resized.width===4&&resized.height===8,"backing resize changes current texture");
const second=document.createElement("canvas");second.width=4;second.height=4;
const other=second.getContext("webgpu");other.configure({device,format:"rgba8unorm",alphaMode:"premultiplied"});
const command=device.createCommandEncoder();
const p=command.beginRenderPass({colorAttachments:[{view:other.getCurrentTexture().createView(),loadOp:"clear",storeOp:"store",clearValue:[0,.5,0,.5]}]});
p.end();device.queue.submit([command.finish()]);
context.unconfigure();
raster.clearRect(0,0,8,8);raster.drawImage(second,0,0);
check([...raster.getImageData(1,1,1,1).data].join()==="0,255,0,128","unconfiguring one canvas leaves shared device and premultiplied sibling intact");
check(context.getConfiguration()===null,"configuration becomes null after unconfigure");
other.unconfigure();device.destroy();await device.lost;
globalThis.webgpuTestsDone=true;
console.log("WEBGPU_CANVAS actualBGRAred=true actualPremulGreenAlpha128=true resize=true sharedDevice=true pngExport=true");
