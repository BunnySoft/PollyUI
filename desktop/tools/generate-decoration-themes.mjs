import { readFileSync, writeFileSync } from 'node:fs';
import { DEFAULT_DESKTOP_THEME, DESKTOP_THEMES } from '../shell/themes.mjs';
import { DECORATION_METRICS, DECORATION_COLORS } from '../shell/theme-schema.mjs';

const number = value => {
  if (!Number.isFinite(value) || value < 0 || value > 10000) throw new Error('Invalid decoration dimension');
  return String(value);
};
const color = value => {
  if (!/^#[0-9a-f]{6}$/i.test(value)) throw new Error('Invalid decoration color');
  return '0xff' + value.slice(1) + 'u';
};
const defaultTheme = DESKTOP_THEMES.findIndex(theme => theme.id === DEFAULT_DESKTOP_THEME);
if (defaultTheme < 0) throw new Error('Missing default decoration theme');
const schema = `/* Generated schema, not theme values. */
#ifndef POLLY_APPEARANCE_FIELDS_H
#define POLLY_APPEARANCE_FIELDS_H
#define PU_APPEARANCE_METRICS(X) \\
${DECORATION_METRICS.map(([field, token, minimum, maximum, scale]) =>
  `    X(${scale === 1 ? 'int' : 'double'}, ${field}, ${token}, ${minimum}, ${maximum}, ${scale})`).join(' \\\n')}
#define PU_APPEARANCE_COLORS(X) \\
${DECORATION_COLORS.map(field => `    X(${field})`).join(' \\\n')}
#endif
`;
const text = `/* Generated by desktop/tools/generate-decoration-themes.mjs. */
#ifndef POLLYWM_DECORATION_THEMES_H
#define POLLYWM_DECORATION_THEMES_H
#include "appearance-config.h"
static const struct PuDecorationTheme pu_decoration_themes[] = {
${DESKTOP_THEMES.map(theme => {
  if (!/^[a-z0-9]+$/.test(theme.id)) throw new Error('Invalid theme ID');
  const w = theme.window;
  return `    { .id = "${theme.id}",
      ${DECORATION_METRICS.map(([field, token]) => `.${field} = ${number(w[token])}`).join(', ')},
      .left_controls = ${w.controls === 'left'}, .round_controls = ${w.controlShape === 'round'},
      .pinstripe = ${w.texture === 'pinstripe'}, .horizontal = ${w.gradientDir === 'horizontal'},
      .glyphs_hover = ${w.glyphsOnHoverOnly},
      .luna = ${w.surfaceStyle === 'luna'},
      .font_family = ${['sans-serif', 'serif', 'monospace'].indexOf(w.fontFamily)},
      .text_align = ${['left', 'center', 'right'].indexOf(w.textAlign)},
      ${DECORATION_COLORS.map(key => `.${key} = ${color(w[key])}`).join(', ')} },`;
}).join('\n')}
};
#define PU_DECORATION_THEME_COUNT (sizeof(pu_decoration_themes) / sizeof(pu_decoration_themes[0]))
#define PU_DECORATION_DEFAULT_THEME ${defaultTheme}
#endif
`;
for (const [file, content] of [['../compositor/decoration-themes.h', text], ['../shared/appearance-fields.h', schema]]) {
  const output = new URL(file, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== content)
      throw new Error('Decoration tokens or schema are stale; regenerate them');
  } else writeFileSync(output, content);
}
