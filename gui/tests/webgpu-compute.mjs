function check(condition, message) { if (!condition) throw Error(message); }
const adapter = await navigator.gpu.requestAdapter();
check(adapter instanceof GPUAdapter, "real native adapter");
console.log("WEBGPU_ADAPTER " + JSON.stringify(adapter.info));
check(adapter.limits.maxBufferSize >= 4, "native limits, not a zero capability fallback");
const device = await adapter.requestDevice();
check(device instanceof GPUDevice && device.queue instanceof GPUQueue, "real device and queue");
const storage = device.createBuffer({size: 4, usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_SRC | GPUBufferUsage.COPY_DST});
const readback = device.createBuffer({size: 4, usage: GPUBufferUsage.MAP_READ | GPUBufferUsage.COPY_DST});
const source = new Uint32Array([0xdeadbeef, 3, 0xffffffff]);
device.queue.writeBuffer(storage, 0, source.subarray(1, 2));
const shader = device.createShaderModule({code: `
@group(0) @binding(0) var<storage, read_write> a: array<u32>;
@compute @workgroup_size(1) fn main() { a[0] = a[0] * 2u + 1u; }
`});
const pipeline = device.createComputePipeline({layout: "auto", compute: {module: shader, entryPoint: "main"}});
const group = device.createBindGroup({layout: pipeline.getBindGroupLayout(0), entries: [{binding: 0, resource: {buffer: storage}}]});
const encoder = device.createCommandEncoder();
const pass = encoder.beginComputePass();
pass.setPipeline(pipeline);
pass.setBindGroup(0, group);
pass.dispatchWorkgroups(1);
pass.end();
encoder.copyBufferToBuffer(storage, 0, readback, 0, 4);
device.queue.submit([encoder.finish()]);
await device.queue.onSubmittedWorkDone();
await readback.mapAsync(GPUMapMode.READ);
check(readback.mapState === "mapped", "native map state");
const mapped = readback.getMappedRange();
check(new Uint32Array(mapped)[0] === 7, "actual WGSL3->7 with typed-array byteOffset/length");
const alias = new Uint8Array(mapped);
readback.unmap();
check(mapped.byteLength === 0 && alias.byteLength === 0, "unmap detaches ArrayBuffer and aliases");
check(readback.mapState === "unmapped", "unmapped native state");
device.pushErrorScope("validation");
device.createBuffer({size: 4, usage: 0});
const error = await device.popErrorScope();
check(error instanceof GPUValidationError && error.message.length > 0, "real native validation error scope");
const mappedWrite = device.createBuffer({size: 8, usage: GPUBufferUsage.COPY_SRC, mappedAtCreation: true});
const range = mappedWrite.getMappedRange();
new Uint32Array(range)[0] = 123;
mappedWrite.destroy();
check(range.byteLength === 0, "destroy detaches mapped native range");
const lost = device.lost;
storage.destroy();
readback.destroy();
device.destroy();
check((await lost).reason === "destroyed", "real native device lost delivery");
globalThis.webgpuTestsDone = true;
console.log("WEBGPU_COMPUTE actual=7 mappedAliasesDetached=true validationScope=true destroyedLoss=true");
